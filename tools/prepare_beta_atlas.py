#!/usr/bin/env python3
"""Project the latest completed Atlas export onto the existing offline reader.

No research, scoring, ROM inference or network access. Unknown values stay absent.
The input must be a completed compact export, never the mutable research/job DB.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import sqlite3
import tomllib


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def prepare(source, legacy, output, database):
    if source.stat().st_size > 32 * 1024 * 1024:
        raise ValueError('Atlas exceeds the existing reader budget')
    old = {g['id']: g for g in tomllib.loads(legacy.read_text())['games']}
    db = sqlite3.connect(source.resolve().as_uri() + '?mode=ro', uri=True)
    try:
        if db.execute('PRAGMA application_id').fetchone()[0] != 1161909324 or db.execute('PRAGMA user_version').fetchone()[0] != 1:
            raise ValueError('Unsupported Atlas schema')
        if db.execute('PRAGMA integrity_check').fetchone()[0] != 'ok' or db.execute('PRAGMA foreign_key_check').fetchall():
            raise ValueError('Atlas integrity failure')
        meta = dict(db.execute('SELECT key,value FROM meta'))
        rows = db.execute('SELECT g.id,g.title,i.platform,COALESCE(e.profile,p.profile) FROM games g JOIN identity_refs i ON i.game_id=g.id JOIN profiles p ON p.game_id=g.id LEFT JOIN profiles_experimental e ON e.game_id=g.id ORDER BY g.id').fetchall()
        text = ['# Generated by tools/prepare_beta_atlas.py; experimental, no human approval.',
                '# Source export: ' + meta['version'],
                '# Metadata title + platform only. Ambiguities remain unmatched.',
                'version = "1.0.0"', '']
        count = 0
        for gid, title, system, profile_text in rows:
            profile = tomllib.loads(profile_text)
            # An identity-only row is not an emotional recommendation profile.
            if not any(k not in ('version', 'knowledge') and (bool(v) if isinstance(v, dict) else v is not None) for k, v in profile.items()):
                continue
            if any(k not in ('version','knowledge','extra','seasons','celebrations') and (type(v) is not int or not 0 <= v <= 240) for k,v in profile.items()):
                raise ValueError('Unsupported profile value')
            previous = old.get(gid, {})
            knowledge = dict(previous.get('profile', {}).get('knowledge', {}))
            knowledge.update(id=gid, provenance='Experimental Atlas ' + meta['version'] + '; source-backed editorial proposals, human review pending. Unknown dimensions remain absent.')
            knowledge.setdefault('confidence', 0)
            sources = [r[0] for r in db.execute('SELECT DISTINCT url FROM cataloger_source_licenses WHERE game_id=? ORDER BY url', (gid,))]
            knowledge['sources'] = list(dict.fromkeys(knowledge.get('sources', []) + sources))[:32]
            aliases = previous.get('aliases', []) if previous.get('title') == title else []
            text += ['[[games]]', 'id = ' + quoted(gid), 'title = ' + quoted(title),
                     'system = ' + quoted(system), 'aliases = ' + quoted(aliases), '[games.profile]']
            for key,value in profile.items():
                if not isinstance(value, dict):
                    text.append(key + ' = ' + quoted(value))
            for key in ('extra', 'seasons', 'celebrations'):
                if profile.get(key):
                    text += ['[games.profile.' + key + ']']
                    text += [quoted(k) + ' = ' + quoted(v) for k,v in sorted(profile[key].items())]
            text += ['[games.profile.knowledge]']
            text += [key + ' = ' + quoted(value) for key,value in sorted(knowledge.items())]
            text += ['']
            count += 1
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text('\n'.join(text))
        database.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, database)
        digest = hashlib.sha256(database.read_bytes()).hexdigest()
        result = dict(version=meta['version'], channel=meta.get('cataloger_channel'),
                      sha256=digest, bytes=database.stat().st_size,
                      catalog_identities=len(rows), recommendation_profiles=count,
                      human_review=False, installed_games_inferred=0,
                      matching='Existing unambiguous metadata title + platform; no fuzzy or filename matching',
                      stable_channel_promoted=False)
        database.with_suffix('.json').write_text(json.dumps(result, indent=2) + '\n')
        return result
    finally:
        db.close()


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, required=True)
    p.add_argument('--legacy', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--database', type=Path, required=True)
    a = p.parse_args()
    print(json.dumps(prepare(a.source, a.legacy, a.output, a.database), indent=2))
