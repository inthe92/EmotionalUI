#!/usr/bin/env python3
"""Production only: one color table -> Slint tokens and existing AA materials.

No image generation, network, runtime preprocessing or new dependencies.
The room PNGs are reviewed inputs, not synthesized by this script.
"""
import json
from pathlib import Path
from room_materials import generate as materials, SURFACES

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / 'assets/scenes/daycycle'
IDS = ['madrugada', 'manana_temprana', 'media_manana', 'primera_tarde',
       'media_tarde', 'anochecer', 'noche', 'neutro']
ALIASES = {'ink': 'primary_text', 'muted': 'secondary_text', 'mark': 'focus_accent',
           'border': 'surface_border'}


def rgba(value):
    value = value.removeprefix('#')
    return tuple(bytes.fromhex(value + ('ff' if len(value) == 6 else '')))


def catalog():
    data = json.loads((FOLDER / 'palettes.json').read_text())
    assert data['version'] == 1
    rows = data['moments']
    assert [r['id'] for r in rows] == IDS
    keys = set(rows[0]['colors'])
    for row in rows:
        assert set(row['colors']) == keys
        for value in row['colors'].values():
            assert len(rgba(value)) == 4
    return rows


def slint_source(rows):
    lines = ['// Generated by tools/daycycle_assets.py; edit palettes.json instead.',
             'export global DaycycleAssets {',
             '    in property <int> palette-index:7;',
             '    in property <int> season-index:4;',
             '    in property <int> palette-next-index:7;',
             '    in property <float> day-mix:0;',
             '    in property <int> weather-index:0;',
             '    in property <int> celebration-index:0;',
             '    in property <float> palette-progress:1;',
             '    in property <[color]> from-colors:[];',
             '    private property <int> index:max(0,min(7,self.palette-index));',
             '    private property <int> next-index:max(0,min(7,self.palette-next-index));']
    response=json.loads((FOLDER/'responses.json').read_text())
    for key in ('seasons','weather','celebrations','weather_window_tints','interior_day_tints','interior_weather_tints','interior_season_tints'):
        lines.append(f'    private property <[color]> response-{key}:['+','.join(response[key])+'];')
    lines += [
        '    private property <color> season-color:self.response-seasons[max(0,min(4,self.season-index))];',
        '    private property <color> weather-color:self.response-weather[max(0,min(4,self.weather-index))];',
        '    private property <color> celebration-color:self.response-celebrations[max(0,min(3,self.celebration-index))];',
        f'    private property <float> season-weight:self.season-index==4?0:{response["season_weight"]};',
        f'    private property <float> weather-weight:self.weather-index==0?0:{response["weather_weight"]};',
        f'    private property <float> celebration-weight:self.celebration-index==0?0:{response["celebration_weight"]};',
        '    out property <color> weather-window-tint:self.response-weather_window_tints[max(0,min(4,self.weather-index))];',
        '    private property <color> interior-day:self.response-interior_day_tints[self.index].mix(self.response-interior_day_tints[self.next-index],1-self.day-mix);',
        f'    private property <color> interior-weather:self.interior-day.mix(self.response-interior_weather_tints[max(0,min(4,self.weather-index))],self.weather-index==0?1:1-{response["interior_weather_mix"]});',
        f'    out property <color> interior-tint:self.index==7?#00000000:self.interior-weather.mix(self.response-interior_season_tints[max(0,min(4,self.season-index))],self.season-index==4?1:1-{response["interior_season_mix"]});',
        '    out property <float> material-coverage:0.94;',
        f'    out property <float> surface-wash:self.season-index==4&&self.weather-index==0&&self.celebration-index==0?0:{response["surface_wash"]};',
        '    out property <color> context-color:(self.weather-index>0?self.weather-color:self.season-color).mix(self.celebration-color,1-self.celebration-weight);']
    names_colors = []
    target_colors = []
    for i, key in enumerate(rows[0]['colors']):
        name = next((alias for alias, token in ALIASES.items() if token == key), key.replace('_', '-'))
        colors = ','.join(row['colors'][key] for row in rows)
        names_colors.append('self.'+name)
        target_colors.append('self.'+name+'-target')
        # Preserve alpha and text luminance. Context affects surfaces/accents only.
        adapt=key not in ('primary_text','secondary_text','shadow')
        lines += [f'    private property <[color]> {name}-values:[{colors}];',
                  f'    private property <color> {name}-day:self.{name}-values[self.index].mix(self.{name}-values[self.next-index],1-self.day-mix);']
        expr=f'self.{name}-day'
        if key=='secondary_text':
            expr += f'.mix(self.context-color,1-{response["secondary_text_weight"]}*(self.season-index<4||self.weather-index>0||self.celebration-index>0?1:0)).with-alpha(self.{name}-day.alpha/255)'
        if adapt:
            expr += '.mix(self.season-color,1-self.season-weight).mix(self.weather-color,1-self.weather-weight).mix(self.celebration-color,1-self.celebration-weight)'
            if key in ('focus_accent','dock_accent','glow'):
                expr += f'.brighter({response["accent_brightness"]})'
            expr += f'.with-alpha(self.{name}-day.alpha/255)'
        lines += [f'    private property <color> {name}-target:{expr};',
                  f'    out property <color> {name}:(self.from-colors.length>{i}?self.from-colors[{i}]:self.{name}-target).mix(self.{name}-target,1-max(0,min(1,self.palette-progress)));']
    seasons=json.loads((FOLDER/'seasons.json').read_text())
    assert seasons['order']==['winter','spring','summer','autumn','unknown']
    lines += ['    out property <[color]> target-colors:['+','.join(target_colors)+'];',
              '    out property <[color]> resolved-colors:['+','.join(names_colors)+'];',
              '    private property <[color]> season-colors:['+','.join(seasons['vegetation_tints'])+'];',
              '    out property <color> vegetation-tint:self.season-colors[max(0,min(4,self.season-index))];',
              '    private property <[color]> daylight-colors:['+','.join(seasons['daylight_tints'])+'];',
              '    out property <color> daylight-tint:self.daylight-colors[max(0,min(4,self.season-index))];',
              '    out property <float> seasonal-light-mix:'+str(seasons['light_mix'])+';',
              '    private property <[float]> season-strengths:['+','.join(str(v) for v in seasons['daylight_strength'])+'];',
              '    out property <float> vegetation-strength:self.season-strengths[self.index]*(1-self.day-mix)+self.season-strengths[self.next-index]*self.day-mix;']
    lines += ['    out property <[image]> backgrounds:[']
    for row in rows:
        lines.append(f'        @image-url("{row["scene"]}"), // {row["id"]}')
    lines.append('    ];')
    names = [name + suffix for name in SURFACES for suffix in ('', '-focus')
             if not (name == 'room-dock' and suffix)]
    names += ['room-dock-selection-' + suffix for suffix in ('active', 'focus', 'active-focus')]
    for name in names:
        slice_ = ',nine-slice(16)' if name.startswith('room-material') else ',nine-slice(12)' if name.startswith('room-tile') else ''
        values = ','.join(f'@image-url("materials/{row["id"]}/{name}.png"{slice_})' for row in rows)
        token = name.removeprefix('room-')
        lines += [f'    private property <[image]> {token}-values:[{values}];',
                  f'    out property <image> {token}:self.{token}-values[self.index];',
                  f'    out property <image> {token}-next:self.{token}-values[self.next-index];']
    return '\n'.join(lines + ['}', ''])


def generate():
    rows = catalog()
    for row in rows:
        c = row['colors']
        materials(FOLDER/'materials'/row['id'], tuple(rgba(c[k]) for k in
                  ('surface_tint', 'surface_bottom', 'surface_border', 'focus_accent')),
                  capsule_top=rgba(c['capsule_tint']),
                  panel_profile=json.loads((FOLDER/'responses.json').read_text())['panel_profile'])
    (FOLDER/'assets.slint').write_text(slint_source(rows))


if __name__ == '__main__':
    generate()
